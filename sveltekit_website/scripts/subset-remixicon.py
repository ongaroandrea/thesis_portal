#!/usr/bin/env python3
"""Subset Remix Icon to the glyphs the portal actually uses.

Scans src/ for `ri-*` class names and the SCSS for raw remixicon code points
(e.g. `content: "\\ea6e"`), then writes:

  src/lib/assets/fonts/remixicon-subset.woff2
  src/lib/assets/scss/plugins/icons/_remixicon-subset.scss

The full source files (remixicon.woff2 and _remixicon.scss) stay in the repo as
the input for this script; only the subset is bundled.

Re-run after adding a new icon:

  python3 -m pip install fonttools brotli
  python3 scripts/subset-remixicon.py
"""
import pathlib
import re
import sys

from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'src'
FULL_SCSS = SRC / 'lib/assets/scss/plugins/icons/_remixicon.scss'
FULL_FONT = SRC / 'lib/assets/fonts/remixicon.woff2'
OUT_SCSS = SRC / 'lib/assets/scss/plugins/icons/_remixicon-subset.scss'
OUT_FONT = SRC / 'lib/assets/fonts/remixicon-subset.woff2'

rule_re = re.compile(r'^\.(ri-[a-z0-9-]+):before \{ content: "\\([0-9a-f]+)"; \}$', re.M)
rules = {name: code for name, code in rule_re.findall(FULL_SCSS.read_text())}

used_classes = set()
raw_codes = set()
for path in SRC.rglob('*'):
	if path.suffix not in {'.svelte', '.js', '.scss', '.html'} or path in (FULL_SCSS, OUT_SCSS):
		continue
	text = path.read_text(errors='ignore')
	used_classes.update(name for name in re.findall(r'\bri-[a-z0-9]+(?:-[a-z0-9]+)*', text) if name in rules)
	if path.suffix == '.scss':
		raw_codes.update(re.findall(r'''["']\\((?:e|f)[0-9a-f]{3})["']''', text))

codes = {int(rules[name], 16) for name in used_classes} | {int(code, 16) for code in raw_codes}
if not codes:
	sys.exit('No remixicon usage found; refusing to write an empty subset.')

options = subset.Options()
options.flavor = 'woff2'
options.layout_features = []
options.name_IDs = ['*']
font = subset.load_font(str(FULL_FONT), options)
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=codes)
subsetter.subset(font)
subset.save_font(font, str(OUT_FONT), options)

header, _, _ = FULL_SCSS.read_text().partition('.ri-24-hours-fill:before')
header = header.replace('remixicon.woff2?t=1718271040674', 'remixicon-subset.woff2')
body = '\n'.join(f'.{name}:before {{ content: "\\{rules[name]}"; }}' for name in sorted(used_classes))
OUT_SCSS.write_text(
	'// GENERATED by scripts/subset-remixicon.py: do not edit by hand.\n'
	+ header.rstrip() + '\n\n' + body + '\n'
)
print(f'{len(used_classes)} classes, {len(codes)} glyphs -> {OUT_FONT.stat().st_size} bytes')
